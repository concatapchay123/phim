  function createIcons({ root = document, attrs = {} } = {}) {
    root.querySelectorAll("[data-lucide]").forEach((element) => {
      const iconName = element.getAttribute("data-lucide");
      const expectedClass = iconName ? `lucide-${iconName}` : "";
      if (element.tagName === "svg" && expectedClass && element.classList.contains(expectedClass)) return;
      replaceElement(element, {
        nameAttr: "data-lucide",
        icons,
        attrs
      });
    });
  }
